def parse_yml(path: Path):
    tree = ET.parse(path)
    shop = tree.getroot().find("shop")
    cats = {c.get("id"): {"name": (c.text or "").strip(), "parent": c.get("parentId")} for c in shop.find("categories")}
    param_names = Counter()
    param_cats = defaultdict(Counter)
    cat_counts = Counter()
    cat_by_id = {cid: info["name"] for cid, info in cats.items()}

    def full_cat(cid):
        info = cats.get(cid, {})
        name = info.get("name") or cid
        parent = info.get("parent")
        if parent and cats.get(parent, {}).get("name"):
            return cats[parent]["name"] + " / " + name
        return name

    for o in shop.find("offers"):
        cid = o.findtext("categoryId")
        cat_counts[cid] += 1
        fcat = full_cat(cid)
        for p in o.findall("param"):
            n = (p.get("name") or "").strip()
            param_names[n] += 1
            param_cats[n][fcat] += 1
    return cats, param_names, param_cats, cat_counts


def split_syns(s: str) -> list[str]:
    if not s:
        return []
    out = []
    for part in s.split("|"):
        t = re.sub(r"\s+", " ", part.strip().lower().replace("ё", "е"))
        if t and t not in out:
            out.append(t)
    return out[:7]


GENERIC_SYN = {
    "в комплекте", "шт", "шт.", "да", "нет", "элемент", "покрытие", "воздуха",
    "книга", "рецептов", "конструкция", "подставка", "измерений", "измерения",
    "камера",
}


def auto_synonyms(yml_name: str) -> list[str]:
    raw = (yml_name or "").strip()
    no_unit = re.sub(r"\s*[\(（][^\)）]{0,60}[\)）]", "", raw)
    no_unit = re.sub(r"\s+", " ", no_unit).strip(" .,-/")
    base = no_unit.replace("ё", "е").lower()
    syns: list[str] = []

    def add(s: str):
        s = re.sub(r"\s+", " ", (s or "").strip().lower().replace("ё", "е")).strip(" .,-/")
        if not s or s in syns or len(s) < 3 or s in GENERIC_SYN:
            return
        syns.append(s)

    add(base)
    add(raw.lower().replace("ё", "е"))
    stripped = base
    for pfx in ("тип ", "вид ", "функция ", "кол-во ", "количество ", "индикация ", "индикатор "):
        if stripped.startswith(pfx):
            add(stripped[len(pfx):])
            stripped = stripped[len(pfx):]
    words = [w for w in re.split(r"[\s/:]+", stripped) if w not in {"шт", "шт.", "да", "нет", "в"}]
    if len(words) >= 3:
        add(" ".join(words[:2]))
        tail = " ".join(words[-2:])
        if tail not in GENERIC_SYN:
            add(tail)
    elif len(words) == 2:
        if words[0] not in GENERIC_SYN:
            add(words[0])
        if len(words[1]) > 3:
            add(words[1])
    add(stripped.replace("-", " "))
    add(stripped.replace("&", " "))
    return syns[:7]


def slug_from_name(name: str) -> str:
    s = re.sub(r"[^A-Za-zА-Яа-я0-9]+", "_", (name or "field").lower())
    s = re.sub(r"_+", "_", s).strip("_")
    return (s or "field")[:40]


